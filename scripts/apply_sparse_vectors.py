"""Applies previously generated sparse vectors from disk checkpoints to Qdrant.

Reads JSONL checkpoints generated by scripts/generate_sparse_vectors.py (e.g. from Google Colab)
and updates existing Qdrant points using client.update_vectors.

Guarantees:
- Existing dense embeddings (BAAI/bge-base-en-v1.5) remain 100% untouched.
- Existing point IDs, payloads, and metadata remain 100% untouched.
- Dry-run by default: requires explicit --apply flag to execute vector updates.
- Resume support via applied_state.json.
"""

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

# Add project root to sys.path
sys.path.insert(0, str(Path(__file__).parent.parent))

from src.ingestion.config import PipelineConfig
from src.ingestion.logging_config import logger
from src.ingestion.vector_store import QdrantManager


def load_checkpoint_records(checkpoint_dir: Path) -> List[Path]:
    """Find all valid sparse vector checkpoint files."""
    files = sorted(checkpoint_dir.glob("sparse_part_*.jsonl"))
    return files


def apply_sparse_checkpoints(
    checkpoint_dir: str,
    collection_name: Optional[str] = None,
    sparse_name: str = "bm25",
    batch_size: int = 256,
    apply: bool = False,
    resume: bool = True,
):
    """Read sparse vector checkpoints and update points in Qdrant."""
    config = PipelineConfig()
    if collection_name:
        config.qdrant_collection = collection_name
    config.sparse_vector_name = sparse_name

    cp_path = Path(checkpoint_dir)
    if not cp_path.exists():
        print(f"❌ Checkpoint directory '{cp_path}' does not exist.")
        return

    checkpoint_files = load_checkpoint_records(cp_path)
    if not checkpoint_files:
        print(f"⚠️ No checkpoint files (sparse_part_*.jsonl) found in '{cp_path}'.")
        return

    print("\n" + "=" * 80)
    print("APPLY SPARSE VECTOR CHECKPOINTS TO QDRANT")
    print("=" * 80)
    print(f"Target Collection:       {config.qdrant_collection}")
    print(f"Sparse Vector Name:      {sparse_name}")
    print(f"Checkpoint Directory:    {cp_path.resolve()}")
    print(f"Found Checkpoint Files:  {len(checkpoint_files)}")
    print(f"Batch Size:              {batch_size}")
    print(f"Execution Mode:          {'[APPLY UPDATES]' if apply else '[DRY-RUN / VERIFY ONLY]'}")
    print("=" * 80)

    manager = QdrantManager(config)

    try:
        info = manager.get_collection_info()
        print(f"Collection Status:       {info.status}")
        print(f"Existing Points Count:   {info.points_count:,}")
        print(f"Dense Vectors Config:    {info.config.params.vectors}")
        print(f"Sparse Vectors Config:   {info.config.params.sparse_vectors or {}}")

        # 1. Verify schema
        sparse_registered = sparse_name in (info.config.params.sparse_vectors or {})
        if not sparse_registered:
            if apply:
                print(f"\nRegistering sparse vector '{sparse_name}' in collection schema...")
                manager.ensure_sparse_vector(sparse_name)
            else:
                print(f"\n⚠️ Sparse vector '{sparse_name}' is not yet registered in schema.")
                print(f"Run 'python scripts/migrate_sparse_schema.py --vector-name {sparse_name} --apply' first,")
                print("or provide '--apply' to register and update automatically.")

        # 2. Check applied state for resume support
        state_file = cp_path / f"applied_state_{config.qdrant_collection}.json"
        already_applied_ids: Set[str] = set()
        if resume and state_file.exists():
            try:
                with open(state_file, "r", encoding="utf-8") as f:
                    state = json.load(f)
                already_applied_ids = set(state.get("applied_ids", []))
                print(f"\nℹ️ Resume: Loaded {len(already_applied_ids):,} already applied point IDs.")
            except Exception as e:
                logger.warning(f"Could not load applied state: {e}")

        # 3. Process checkpoint records
        total_records_seen = 0
        total_applied_this_session = 0
        batch_updates: List[Tuple[str, List[int], List[float]]] = []
        start_time = time.perf_counter()

        for cp_file in checkpoint_files:
            print(f"\nReading checkpoint: {cp_file.name} ...")
            with open(cp_file, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    record = json.loads(line)
                    pt_id = str(record["id"])
                    total_records_seen += 1

                    if resume and pt_id in already_applied_ids:
                        continue

                    batch_updates.append((pt_id, record["indices"], record["values"]))

                    if len(batch_updates) >= batch_size:
                        if apply:
                            manager.update_point_sparse_vectors(
                                updates=batch_updates,
                                vector_name=sparse_name,
                            )
                            for item in batch_updates:
                                already_applied_ids.add(item[0])

                            # Update state file periodically
                            if len(already_applied_ids) % 1000 == 0:
                                _save_applied_state(state_file, already_applied_ids)

                        total_applied_this_session += len(batch_updates)
                        elapsed = time.perf_counter() - start_time
                        rate = total_applied_this_session / elapsed if elapsed > 0 else 0.0

                        print(
                            f"  Applied: {total_applied_this_session:,} points | "
                            f"Rate: {rate:.1f} pts/s | "
                            f"Elapsed: {elapsed / 60:.1f}m"
                        )
                        batch_updates.clear()

        # Flush remaining updates
        if batch_updates:
            if apply:
                manager.update_point_sparse_vectors(
                    updates=batch_updates,
                    vector_name=sparse_name,
                )
                for item in batch_updates:
                    already_applied_ids.add(item[0])
                _save_applied_state(state_file, already_applied_ids)

            total_applied_this_session += len(batch_updates)
            batch_updates.clear()

        elapsed_total = time.perf_counter() - start_time

        print("\n" + "=" * 80)
        print("CHECKPOINT APPLICATION SUMMARY")
        print("=" * 80)
        print(f"Total Checkpoint Records:   {total_records_seen:,}")
        print(f"Total Applied This Session: {total_applied_this_session:,}")
        print(f"Total Cumulative Applied:   {len(already_applied_ids):,}")
        print(f"Time Taken:                 {elapsed_total / 60:.2f} minutes")
        if not apply:
            print("\n[DRY RUN COMPLETE]: No changes were made to Qdrant.")
            print("To apply sparse vectors to Qdrant points, run with '--apply':")
            print("    python scripts/apply_sparse_vectors.py --apply")
        else:
            print("\n✅ Sparse vectors applied successfully to Qdrant!")
            print("Dense vectors, payloads, and point IDs are 100% intact.")
        print("=" * 80 + "\n")

    except Exception as e:
        logger.exception("Failed applying sparse checkpoints")
        print(f"\n❌ Error applying sparse checkpoints: {e}")
    finally:
        manager.close()


def _save_applied_state(state_file: Path, applied_ids: Set[str]):
    """Save applied state atomically."""
    temp_file = state_file.with_suffix(".tmp")
    with open(temp_file, "w", encoding="utf-8") as f:
        json.dump(
            {
                "applied_ids": list(applied_ids),
                "count": len(applied_ids),
                "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            },
            f,
        )
    temp_file.replace(state_file)


def store_as_new_collection(
    checkpoint_dir: str,
    collection_name: str = "qa_knowledge_sparse",
    sparse_name: str = "bm25",
    qdrant_path: Optional[str] = None,
    chunks_file: Optional[str] = None,
    batch_size: int = 256,
    apply: bool = False,
    resume: bool = True,
):
    """Store sparse vectors into a dedicated new Qdrant collection."""
    from qdrant_client import QdrantClient, models

    cp_path = Path(checkpoint_dir)
    if not cp_path.exists():
        print(f"❌ Checkpoint directory '{cp_path}' does not exist.")
        return

    checkpoint_files = load_checkpoint_records(cp_path)
    if not checkpoint_files:
        print(f"⚠️ No checkpoint files (sparse_part_*.jsonl) found in '{cp_path}'.")
        return

    target_qdrant_path = qdrant_path or "data/qdrant_sparse_db"
    Path(target_qdrant_path).mkdir(parents=True, exist_ok=True)

    # Auto-detect default chunks file if present
    if not chunks_file and Path("data/chunks_for_colab.jsonl").exists():
        chunks_file = "data/chunks_for_colab.jsonl"

    print("\n" + "=" * 80)
    print("STORE SPARSE VECTORS IN NEW QDRANT COLLECTION")
    print("=" * 80)
    print(f"Target Collection:       {collection_name}")
    print(f"Qdrant Storage Path:     {Path(target_qdrant_path).resolve()}")
    print(f"Sparse Vector Name:      {sparse_name}")
    print(f"Found Checkpoint Files:  {len(checkpoint_files)}")
    print(f"Chunks File (for text):  {chunks_file if chunks_file else 'None (sparse vectors only)'}")
    print(f"Batch Size:              {batch_size}")
    print(f"Execution Mode:          {'[APPLY / CREATE & STORE]' if apply else '[DRY-RUN / VERIFY ONLY]'}")
    print("=" * 80)

    # 1. Load chunk texts if available
    text_lookup = {}
    if chunks_file:
        c_path = Path(chunks_file)
        if c_path.exists():
            print(f"\nLoading chunk texts from '{c_path.name}' for payloads...")
            with open(c_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line:
                        rec = json.loads(line)
                        text_lookup[str(rec.get("id"))] = rec.get("text", "")
            print(f"Loaded {len(text_lookup):,} chunk text entries.")
        else:
            print(f"Notice: Chunks file '{c_path}' not found. Points will be stored without text.")

    if not apply:
        total_records = 0
        for cp_file in checkpoint_files:
            with open(cp_file, "r", encoding="utf-8") as f:
                total_records += sum(1 for line in f if line.strip())
        print(f"\n[DRY RUN SUMMARY]: Found {total_records:,} sparse vector points.")
        print(f"To create collection '{collection_name}' and store points, re-run with '--apply':")
        print(f"    python scripts/apply_sparse_vectors.py --as-new-collection {collection_name} --apply\n")
        return

    client = QdrantClient(path=target_qdrant_path)
    try:
        # 2. Check / Create collection
        existing_cols = [c.name for c in client.get_collections().collections]
        if collection_name not in existing_cols:
            print(f"\nCreating collection '{collection_name}' with sparse vector '{sparse_name}'...")
            client.create_collection(
                collection_name=collection_name,
                vectors_config={},
                sparse_vectors_config={sparse_name: models.SparseVectorParams()},
            )
            print(f"✅ Collection '{collection_name}' created successfully.")
        else:
            print(f"\nCollection '{collection_name}' already exists. Storing points...")

        # 3. Resume state
        state_file = cp_path / f"applied_new_state_{collection_name}.json"
        already_applied_ids: Set[str] = set()
        if resume and state_file.exists():
            try:
                with open(state_file, "r", encoding="utf-8") as f:
                    state = json.load(f)
                    already_applied_ids = set(state.get("applied_ids", []))
                print(f"ℹ️ Resume: {len(already_applied_ids):,} points already stored previously.")
            except Exception as e:
                logger.warning(f"Could not load state: {e}")

        total_stored_this_session = 0
        batch_points: List[models.PointStruct] = []
        start_time = time.perf_counter()

        for cp_file in checkpoint_files:
            print(f"\nReading checkpoint: {cp_file.name} ...")
            with open(cp_file, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    record = json.loads(line)
                    pt_id = str(record["id"])

                    if resume and pt_id in already_applied_ids:
                        continue

                    payload = {}
                    if pt_id in text_lookup:
                        payload["text"] = text_lookup[pt_id]

                    batch_points.append(
                        models.PointStruct(
                            id=pt_id,
                            vector={
                                sparse_name: models.SparseVector(
                                    indices=record["indices"],
                                    values=record["values"],
                                )
                            },
                            payload=payload if payload else None,
                        )
                    )

                    if len(batch_points) >= batch_size:
                        client.upsert(
                            collection_name=collection_name,
                            points=batch_points,
                            wait=True,
                        )
                        for p in batch_points:
                            already_applied_ids.add(str(p.id))

                        total_stored_this_session += len(batch_points)
                        elapsed = time.perf_counter() - start_time
                        rate = total_stored_this_session / elapsed if elapsed > 0 else 0.0
                        print(
                            f"  Stored: {total_stored_this_session:,} points | "
                            f"Rate: {rate:.1f} pts/s | "
                            f"Elapsed: {elapsed / 60:.1f}m"
                        )
                        batch_points.clear()

                        if len(already_applied_ids) % 1000 == 0:
                            _save_applied_state(state_file, already_applied_ids)

        if batch_points:
            client.upsert(
                collection_name=collection_name,
                points=batch_points,
                wait=True,
            )
            for p in batch_points:
                already_applied_ids.add(str(p.id))
            total_stored_this_session += len(batch_points)
            batch_points.clear()
            _save_applied_state(state_file, already_applied_ids)

        elapsed_total = time.perf_counter() - start_time
        print("\n" + "=" * 80)
        print("NEW COLLECTION STORAGE SUMMARY")
        print("=" * 80)
        print(f"Collection:                 {collection_name}")
        print(f"Storage Path:               {Path(target_qdrant_path).resolve()}")
        print(f"Total Stored This Session:  {total_stored_this_session:,}")
        print(f"Total Cumulative In Col:    {len(already_applied_ids):,}")
        print(f"Time Taken:                 {elapsed_total / 60:.2f} minutes")
        print(f"✅ Sparse collection '{collection_name}' is ready for BM25 retrieval!")
        print("=" * 80 + "\n")

    finally:
        client.close()


def main():
    parser = argparse.ArgumentParser(
        description="Apply generated sparse vector checkpoints to Qdrant (existing or new collection)."
    )
    parser.add_argument(
        "--checkpoint-dir",
        type=str,
        default="data/sparse_checkpoints",
        help="Directory containing sparse_part_*.jsonl files (default: data/sparse_checkpoints).",
    )
    parser.add_argument(
        "--collection",
        type=str,
        default=None,
        help="Target collection name (defaults to QDRANT_COLLECTION in config).",
    )
    parser.add_argument(
        "--as-new-collection",
        type=str,
        nargs="?",
        const="qa_knowledge_sparse",
        default=None,
        help="Store sparse vectors into a new dedicated sparse collection (e.g. qa_knowledge_sparse).",
    )
    parser.add_argument(
        "--chunks-file",
        type=str,
        default=None,
        help="Path to chunks JSONL file (e.g. data/chunks_for_colab.jsonl) to include text payload.",
    )
    parser.add_argument(
        "--qdrant-path",
        type=str,
        default=None,
        help="Path to local Qdrant database folder (defaults to config or data/qdrant_sparse_db).",
    )
    parser.add_argument(
        "--sparse-name",
        type=str,
        default="bm25",
        help="Sparse vector name in Qdrant (default: 'bm25').",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=256,
        help="Batch size for vector operations (default: 256).",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        default=False,
        help="Actually apply updates / create collection in Qdrant. If omitted, runs in dry-run mode.",
    )
    parser.add_argument(
        "--no-resume",
        action="store_true",
        default=False,
        help="Ignore state file and re-process all points.",
    )

    args = parser.parse_args()

    if args.as_new_collection:
        store_as_new_collection(
            checkpoint_dir=args.checkpoint_dir,
            collection_name=args.as_new_collection,
            sparse_name=args.sparse_name,
            qdrant_path=args.qdrant_path,
            chunks_file=args.chunks_file,
            batch_size=args.batch_size,
            apply=args.apply,
            resume=not args.no_resume,
        )
    else:
        apply_sparse_checkpoints(
            checkpoint_dir=args.checkpoint_dir,
            collection_name=args.collection,
            sparse_name=args.sparse_name,
            batch_size=args.batch_size,
            apply=args.apply,
            resume=not args.no_resume,
        )


if __name__ == "__main__":
    main()
